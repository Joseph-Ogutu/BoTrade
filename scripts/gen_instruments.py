"""Generate docs/instruments.md from docs/evidence/active_symbols_brief.json (public endpoint response)."""
import collections
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = json.loads((root / "docs/evidence/active_symbols_brief.json").read_text())["active_symbols"]

by_market = collections.OrderedDict()
for s in sorted(data, key=lambda x: (x["market"] != "synthetic_index", x["market"], x["submarket"], x["underlying_symbol"])):
    by_market.setdefault(s["market"], collections.OrderedDict()).setdefault(s["submarket"], []).append(s)

out = ["# Instruments returned by active_symbols (public endpoint)", "",
       "Generated by scripts/gen_instruments.py from docs/evidence/active_symbols_brief.json. Do not edit by hand.",
       "Query made 2026-11-01 about 00:00 to 01:00 local (Sat 2026-10-31 about 21:00 to 22:00 GMT, a weekend),",
       "so `closed` flags reflect market hours at that moment, not permanent availability.",
       "Availability for the DEMO account may differ from the public view. UNVERIFIED until checked with the demo PAT.", "",
       f"Total symbols: {len(data)}. Markets: " + ", ".join(f"{m} ({sum(len(v) for v in subs.values())})" for m, subs in by_market.items()), ""]
for market, subs in by_market.items():
    kind = "synthetic (Deriv-generated)" if market == "synthetic_index" else "NON-synthetic by Deriv's market classification"
    out += [f"## {market}: {kind}", ""]
    for sub, items in subs.items():
        out += [f"### {sub}", "", "| symbol | name | pip | status when queried |", "|---|---|---|---|"]
        for s in items:
            status = "open" if s["exchange_is_open"] else "closed"
            if s["is_trading_suspended"]:
                status += ", suspended"
            out.append(f"| `{s['underlying_symbol']}` | {s['underlying_symbol_name']} | {s['pip_size']} | {status} |")
        out.append("")
(root / "docs/instruments.md").write_text("\n".join(out))
