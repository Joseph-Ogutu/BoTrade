"""Print the planning n_min table from docs/kill-criterion.md section 3.

Usage: python scripts/power_table.py > docs/power-table.md
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from derivbot.stats.edge import breakeven_p, required_n  # noqa: E402

DELTA, POWER, FAMILY_ALPHA = 0.02, 0.80, 0.05

print("# Planning n_min table")
print()
print(f"Generated by scripts/power_table.py. delta={DELTA}, power={POWER}, family alpha={FAMILY_ALPHA}.")
print("Planning only. The binding n_min uses the real r from proposal responses.")
print()
print("| r | p_be | n_min (K=1) | n_min (K=20) |")
print("|---|---|---|---|")
for r in (0.80, 0.85, 0.90, 0.95):
    p0 = breakeven_p(r)
    n1 = required_n(p0, DELTA, FAMILY_ALPHA, POWER)
    n20 = required_n(p0, DELTA, FAMILY_ALPHA / 20, POWER)
    print(f"| {r:.2f} | {p0:.4f} | {n1} | {n20} |")
