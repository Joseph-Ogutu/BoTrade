"""Generate docs/hypotheses/*.md and INDEX.md from the code's own defaults and registered grids (so docs cannot drift).
Run: python scripts/gen_hypotheses.py. A test fails if the committed files differ from the generated ones."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from derivbot.signals import registry  # noqa: E402
from derivbot.signals.strategies import default_strategies  # noqa: E402

TEXT = {
    "ema_trend": ("Price trends persist long enough after a fast EMA crosses the slow EMA that a 5 tick CALL (upward cross) or PUT (downward cross) wins more often than break-even.",
                  "EMA(fast) and EMA(slow) are computed over the last 5 x slow ticks. CALL when fast crosses above slow at this tick, PUT when it crosses below."),
    "rsi_bollinger": ("After a move outside the Bollinger band with RSI at an extreme, price reverts within 5 ticks often enough to beat break-even.",
                      "Bollinger band over bb_period ticks (mean +/- bb_k standard deviations) and a simple-average RSI over rsi_period ticks. CALL if price is below the lower band and RSI < rsi_low; PUT if above the upper band and RSI > rsi_high."),
    "vol_breakout": ("A tick move larger than k standard deviations of the preceding moves continues over the next 5 ticks.",
                     "Standard deviation of the previous lookback tick changes. CALL if the last change exceeds +k sd, PUT if below -k sd."),
    "regime_ema_trend": ("EMA trend signals are better in trending regimes than overall.", "Passes the EMA trend signal only when the efficiency ratio of the last 30 ticks is at least the threshold."),
    "regime_vol_breakout": ("Volatility breakouts are better in trending regimes than overall.", "Passes the breakout signal only when the efficiency ratio of the last 30 ticks is at least the threshold."),
    "regime_rsi_bollinger": ("Mean reversion is better in ranging regimes than overall.", "Passes the RSI/Bollinger signal only when the efficiency ratio of the last 30 ticks is below the threshold."),
    "adaptive_selector": ("Recent hit rate of a strategy predicts its next-trade hit rate.", "Re-scores the three base strategies on already-settled past decisions and follows the best one if its hit rate is at least 0.55 over at least 8 decisions."),
}


def render(name: str, strat) -> str:
    claim, rule = TEXT[name]
    points = registry.grid_points(name)
    meta = {"id": name, "version": strat.version, "contract_types": ["CALL", "PUT"], "duration_ticks": strat.duration_ticks,
            "params": strat.params, "grid": registry.GRIDS[name], "grid_points": len(points),
            "symbols": list(registry.CONFIRMATORY_SYMBOLS), "variants_counted": len(points) * len(registry.CONFIRMATORY_SYMBOLS)}
    return f"""# Hypothesis: {name}

Generated by scripts/gen_hypotheses.py from the code. Registered before any real-data run (kill-criterion Amendment 4).

## Claim

{claim}

## Rule

{rule} Duration: {strat.duration_ticks} ticks. Contracts: CALL and PUT only; the signal decides the direction.

## Fixed parameters (conventional values, not chosen from data)

```json HYPOTHESIS
{json.dumps(meta, indent=2, sort_keys=True)}
```

## Expected effect

None expected on synthetic indices, which are random by design (HANDBOOK 4.2, UNVERIFIED against Deriv's own description). The null is a win rate at or below 0.5, below the break-even rate of about 0.513 at r = 0.95. This hypothesis is a test that must be allowed to fail.

## Falsified if

On the locked holdout the kill criterion is not met: the Wilson lower bound does not exceed the break-even win rate after correction for K variants, or expectancy is not positive at the observed and at the r - 0.05 payout, or the effect is absent in either time block.

## Not allowed

Changing any parameter or grid point after seeing real-data results. Adding variants without adding them to the index and K. Running on real ticks before Gate 1 has reported and the owner has approved in docs/approvals.md.
"""


def main() -> None:
    d = ROOT / "docs" / "hypotheses"
    d.mkdir(exist_ok=True)
    strategies = default_strategies()
    rows = []
    for name in registry.GRIDS:
        (d / f"{name}.md").write_text(render(name, strategies[name]))
        rows.append((name, len(registry.grid_points(name))))
    idx = ["# Registered hypotheses and the variant count K", "",
           "Generated by scripts/gen_hypotheses.py. K is the number of variants the multiple-testing correction must count (kill-criterion v1 section 2, Amendment 4).",
           "", "| hypothesis | grid points | symbols | variants counted |", "|---|---|---|---|"]
    for name, n in rows:
        idx.append(f"| [{name}]({name}.md) | {n} | {len(registry.CONFIRMATORY_SYMBOLS)} | {n * len(registry.CONFIRMATORY_SYMBOLS)} |")
    idx += ["", f"Total K = {registry.total_k()} (variants per symbol {registry.variants_per_symbol()}, symbols {len(registry.CONFIRMATORY_SYMBOLS)}, one fixed duration of {registry.DURATION_TICKS} ticks).", ""]
    (d / "INDEX.md").write_text("\n".join(idx))
    (d / "README.md").write_text("# Hypotheses\n\nOne file per hypothesis, generated from the code (scripts/gen_hypotheses.py). Rules: see kill-criterion Amendment 4. See INDEX.md for K.\n")


if __name__ == "__main__":
    main()
