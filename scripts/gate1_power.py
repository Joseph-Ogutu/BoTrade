"""Generate docs/power-gate1.md from the stamped evidence files. Nothing in the output is typed by hand.

Break-even win rate is p_be = stake / payout, taken from real proposal quotes captured on the public endpoint.
Usage: python scripts/gate1_power.py > docs/power-gate1.md
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from derivbot.stats.edge import required_n  # noqa: E402

batch = json.loads((ROOT / "docs/evidence/public_probe_batch.json").read_text())
resp, ev = batch["responses"], batch["_evidence"]

QUOTES = [  # (label, evidence key)
    ("DIGITEVEN 5t, stake 1.00", "1HZ100V:DIGITEVEN:None"),
    ("DIGITODD 5t, stake 1.00", "1HZ100V:DIGITODD:None"),
    ("DIGITUNDER 5 5t, stake 1.00", "1HZ100V:DIGITUNDER:5"),
    ("DIGITOVER 5 5t, stake 1.00", "1HZ100V:DIGITOVER:5"),
    ("DIGITMATCH 5 5t, stake 1.00", "1HZ100V:DIGITMATCH:5"),
    ("DIGITDIFF 5 5t, stake 1.00", "1HZ100V:DIGITDIFF:5"),
    ("DIGITEVEN 5t, stake 0.35 (minimum)", "1HZ100V:DIGITEVEN:stake0.35"),
]
DELTA, POWER, FAMILY = 0.02, 0.80, 0.05

print("# Gate 1 break-even and power tables (generated)")
print()
print("Generated by scripts/gate1_power.py from docs/evidence/public_probe_batch.json.")
print(f"Quotes captured {ev['captured_at_utc']} (UTC) on the public endpoint, symbol 1HZ100V (R_100 quotes were identical).")
print("These are PUBLIC-endpoint quotes. Quotes for the demo account are UNVERIFIED and may differ.")
print()
print("## Break-even win rate from observed payouts")
print()
print("p_be = stake / payout. r = (payout - stake) / stake.")
print()
print("| contract | stake | payout | r | p_be |")
print("|---|---|---|---|---|")
pbe = {}
for label, key in QUOTES:
    p = resp[key]["proposal"]
    stake, payout = p["ask_price"], p["payout"]
    r = (payout - stake) / stake
    pbe[label] = stake / payout
    print(f"| {label} | {stake:.2f} | {payout:.2f} | {r:.4f} | {stake / payout:.6f} |")
print()
print("The minimum-stake quote has the worse ratio (DIGITEVEN: r 0.8857 at 0.35 against 0.95 at 1.00).")
print("Quotes at the minimum stake were observed for DIGITEVEN only. For other contracts at 0.35 the ratio is UNVERIFIED.")
print()

lo, hi = pbe["DIGITEVEN 5t, stake 1.00"], pbe["DIGITEVEN 5t, stake 0.35 (minimum)"]
print("## Edge gate n_min (kill-criterion v1 formula)")
print()
print(f"One-sided, delta = {DELTA}, power = {POWER}, family alpha = {FAMILY} divided by K variants.")
print()
print("| p_be used | K | alpha | n_min |")
print("|---|---|---|---|")
for name, p in (("stake 1.00 (0.512821)", lo), ("stake 0.35 (0.530303)", hi)):
    for k in (1, 8, 20):
        print(f"| {name} | {k} | {FAMILY / k:.5f} | {required_n(p, DELTA, FAMILY / k, POWER)} |")
print()
print("## Gate 1 structure test: smallest parity bias that would beat break-even")
print()
print("Two-sided test of P(even) = 0.5 against P(even) = p_be, alpha = 0.05 / 8 (Bonferroni bound on the Holm family of 8), power 0.80.")
print()
print("| effect to detect | P(even) | n digits needed |")
print("|---|---|---|")
for name, p in (("break-even at stake 1.00", lo), ("break-even at stake 0.35", hi)):
    n = required_n(0.5, p - 0.5, (0.05 / 8) / 2, 0.80)
    print(f"| {name} | {p:.6f} | {n} |")
print()
print("## Feasibility: ticks per day at the nominal rate")
print()
print("| symbol | nominal interval | ticks per day | days to reach 100,000 ticks |")
print("|---|---|---|---|")
for sym, interval in (("1HZ100V", 1), ("R_100", 2)):
    per_day = 86400 // interval
    print(f"| {sym} | {interval} s | {per_day} | {100000 / per_day:.1f} |")
